// emitMain parses the simulation directives (see directives.go), emits
// phase_log now that the .save() signal list is known, then writes main():
// builds the System (two-pass register/finalize/stamp — see netlist.go),
// wires up the Solver/API/VM, sets the phase function pointers, configures
// the logger, selects the solver strategy, and calls vm_run.
func (g *generator) emitMain() error {
	cfg, err := g.parseSimConfig()
	if err != nil {
		return err
	}

	// Validates the .solver name; the runtime selects by the Hover name itself.
	if _, err := solverStructName(cfg.solverType); err != nil {
		return err
	}

	g.emitPhaseLog(cfg.saveVMSignals, cfg.saveBranchCurrents)

	if g.LibraryMode {
		return g.emitLibraryMain(cfg)
	}

	g.raw(`// ── MAIN ─────────────────────────────────────────────────────────────────────`)
	g.raw(`int main(void) {`)
	g.push()
	g.line("hvr::Sim sim;")
	g.emitSimSetup(cfg, "return 1;")
	g.raw("")
	// Exit codes: 1 = the simulator could not be set up (e.g. unknown solver),
	// 2 = it ran but stopped early — a solver gave up, or .ac had no operating
	// point to linearise around. Results written before that are kept.
	g.line("int rc = 0;")
	if cfg.acEnabled {
		// AC first; then the transient only if the deck asked for one (a deck
		// with .ac alone skips the default transient).
		g.line("if (!sim.run_ac()) rc = 2;")
		if cfg.tranPresent {
			g.line("if (!sim.run()) rc = 2;")
		}
	} else {
		g.line("if (!sim.run()) rc = 2;")
	}
	g.line("return rc;")

	g.pop()
	g.raw("}")

	return nil
}

// emitSimSetup emits the statements that build and configure the simulation
// held in `sim` (an hvr::Sim — runtime/hover_sim.hpp): the two-pass netlist
// build, VM wiring, the .ac sweep, phase hooks, the logger's columns and the
// solver. Shared by main() and the --hovercraft library's hvr_boot(), which
// run exactly this sequence and differ only in what happens after it.
//
// onSolverError is the statement to run if the runtime rejects the solver
// name — which only happens if compiler and runtime disagree about which
// solvers exist (the runtime prints why). It differs because main() returns
// int and hvr_boot() returns void.
func (g *generator) emitSimSetup(cfg simConfig, onSolverError string) {
	g.line("// Build system — two-pass: register then stamp")
	g.line("sim.init_system(%s);", cfg.tStep)
	g.line("register_netlist(sim);  // pass 1: register all nodes and branches")
	g.line("sim.finalize_system();  // size the MNA matrices to the exact count")
	g.line("stamp_netlist(sim);     // pass 2: stamp values into them")
	g.raw("")

	if len(g.stateSlots) > 0 {
		g.line("sim.init_state_slots(%d);  // ddt()/idt() call sites", len(g.stateSlots))
	}
	g.line("sim.init_vm(%s, %s, %t, %t);", cfg.tStep, cfg.tEnd, cfg.zcdEnabled, cfg.opEnabled)
	if cfg.acEnabled {
		g.line("// .ac small-signal sweep")
		g.line("sim.set_ac(%d, %d, %s, %s, %d);", cfg.acSweep, cfg.acPoints, cfg.acFStart, cfg.acFStop, len(cfg.saveVMSignals))
		for _, n := range cfg.saveMNANodes {
			g.line("sim.add_ac_node(%s);", cStr(n))
		}
		for _, b := range cfg.saveBranchCurrents {
			g.line("sim.add_ac_branch(%s);", cStr(b))
		}
	}
	g.line("sim.set_phases(phase_structural, phase_digital, phase_analog, phase_b,")
	g.line("               phase_log, save_state_vars, restore_state_vars);")
	for _, c := range cfg.clocks {
		g.line("sim.add_clock(%s, %s, %s);", cStr(c.name), formatDoubleLiteral(c.period), c.phaseFunc())
	}
	g.raw("")

	g.line("// Logger")
	for _, n := range cfg.saveMNANodes {
		g.line("sim.log_node(%s);", cStr(n))
	}
	for _, s := range cfg.loggerSignalList() {
		g.line("sim.log_signal(%s);", cStr(s))
	}
	g.line("sim.init_logger();")
	g.raw("")

	g.line("// Solver")
	g.line("if (!sim.set_solver(%s)) %s", cStr(cfg.solverType), onSolverError)
	g.emitSolverTuningOverrides(cfg)
}

// formatStateInitializer produces the file-scope static initializer for a state
// variable. Constants and array literals are folded as before. A pointer/scalar
// initialized from an EXTERN call (the opaque-pointer pattern) is emitted as the
// real call: a static initialized from an extern function runs once at startup
// and needs no vm. Any other non-constant initializer can't run safely at file
// scope (a Hover-function call would need vm before main), so it falls back to 0.
func (g *generator) formatStateInitializer(ht hoverType, si stateInit) string {
	if ht.isArray() {
		return g.formatArrayLiteral(ht.elem, ht.structName, ht.dims, si.value)
	}
	if ht.elem == CStruct {
		return g.formatStructLiteral(ht.structName, si.value)
	}
	switch v := si.value.(type) {
	case nil:
		if ht.isPointer() {
			return "0"
		}
		return formatTypedLiteral(0.0, ht.elem)
	case *ast.NumberExpression:
		return formatTypedLiteral(elaborator.ParseEngineering(v.Value), ht.elem)
	case *ast.CallExpression:
		if decl := g.lookupFunctionDecl(callExpressionName(v.Function), si.logic); decl != nil && decl.IsExtern {
			code, ct := g.emitExpr(v, si.logic)
			return castToHover(code, ct, ht)
		}
	}
	if ht.isPointer() {
		return "0"
	}
	return formatTypedLiteral(0.0, ht.elem)
}
